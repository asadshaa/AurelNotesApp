package com.aurel.notes.core.security

import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.nio.ByteBuffer
import java.security.KeyStore
import java.security.SecureRandom
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import javax.crypto.spec.SecretKeySpec

/**
 * Provides AES-256 GCM encryption and decryption for private notes and vault storage.
 * Integrates with AndroidKeyStore for hardware-backed keys, with fallback support for JVM unit testing.
 */
class VaultEncryptionHelper(
    private val customSecretKey: SecretKey? = null
) {
    companion object {
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val KEY_ALIAS = "aurel_vault_master_key"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val IV_LENGTH_BYTES = 12
        private const val TAG_LENGTH_BITS = 128
        const val VAULT_PREFIX = "AUREL_ENC_V1:"
    }

    private val secureRandom = SecureRandom()

    private fun getOrCreateSecretKey(): SecretKey {
        if (customSecretKey != null) return customSecretKey

        return try {
            val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
            if (keyStore.containsAlias(KEY_ALIAS)) {
                val entry = keyStore.getEntry(KEY_ALIAS, null) as KeyStore.SecretKeyEntry
                entry.secretKey
            } else {
                generateKeyStoreKey()
            }
        } catch (_: Exception) {
            // Fallback for JVM unit tests where AndroidKeyStore provider is absent
            generateSoftwareKey()
        }
    }

    private fun generateKeyStoreKey(): SecretKey {
        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            ANDROID_KEYSTORE
        )
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
            .build()
        keyGenerator.init(spec)
        return keyGenerator.generateKey()
    }

    private fun generateSoftwareKey(): SecretKey {
        val keyGen = KeyGenerator.getInstance("AES")
        keyGen.init(256, secureRandom)
        return keyGen.generateKey()
    }

    /**
     * Encrypts plaintext string using AES/GCM/NoPadding with a randomized 12-byte IV.
     * Returns Base64-encoded payload prefixed with VAULT_PREFIX.
     */
    fun encrypt(plainText: String): String {
        if (plainText.isEmpty()) return ""
        val secretKey = getOrCreateSecretKey()
        val iv = ByteArray(IV_LENGTH_BYTES)
        secureRandom.nextBytes(iv)

        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey, GCMParameterSpec(TAG_LENGTH_BITS, iv))

        val cipherBytes = cipher.doFinal(plainText.toByteArray(Charsets.UTF_8))
        val buffer = ByteBuffer.allocate(iv.size + cipherBytes.size)
        buffer.put(iv)
        buffer.put(cipherBytes)

        val encoded = java.util.Base64.getEncoder().encodeToString(buffer.array())
        return "$VAULT_PREFIX$encoded"
    }

    /**
     * Decrypts an encrypted payload generated by encrypt().
     * Throws an exception if authentication tag verification fails (data tampered).
     */
    fun decrypt(encryptedPayload: String): String {
        if (encryptedPayload.isEmpty()) return ""
        val data = if (encryptedPayload.startsWith(VAULT_PREFIX)) {
            encryptedPayload.removePrefix(VAULT_PREFIX)
        } else {
            encryptedPayload
        }

        val combinedBytes = java.util.Base64.getDecoder().decode(data)
        if (combinedBytes.size < IV_LENGTH_BYTES) {
            throw IllegalArgumentException("Invalid encrypted payload: buffer too short")
        }

        val iv = ByteArray(IV_LENGTH_BYTES)
        System.arraycopy(combinedBytes, 0, iv, 0, IV_LENGTH_BYTES)

        val cipherTextSize = combinedBytes.size - IV_LENGTH_BYTES
        val cipherText = ByteArray(cipherTextSize)
        System.arraycopy(combinedBytes, IV_LENGTH_BYTES, cipherText, 0, cipherTextSize)

        val secretKey = getOrCreateSecretKey()
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey, GCMParameterSpec(TAG_LENGTH_BITS, iv))

        val decryptedBytes = cipher.doFinal(cipherText)
        return String(decryptedBytes, Charsets.UTF_8)
    }

    fun isEncrypted(text: String): Boolean {
        return text.startsWith(VAULT_PREFIX)
    }
}
